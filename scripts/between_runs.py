"""
Compares two INDEPENDENT full matrices of the same binaries, and asks the only question
that matters for a published verdict: does the verdict survive re-running the experiment?

WHY THIS EXISTS. `analyze.py` reports an interval built from the 11 launches inside one
matrix. That interval captures launch-to-launch variation. It does NOT capture the
machine's state drifting between one matrix and the next -- thermal history, background
load, whatever the OS decided to do that afternoon. If that drift is comparable to the
effect being claimed, a tight within-matrix interval is false precision, and the honest
uncertainty is wider than anything `analyze.py` can see.

The Windows binaries did not change between the two matrices committed to this repo. The
MSVC flags are identical, the C++ source is identical, and the only C# change was to the
provenance string written after the timed region. So the two runs differ by machine state
alone, which makes them a reproducibility experiment rather than two versions of a
benchmark.

WHAT IT REPORTS.
  1. The per-cell change from run A to run B, and the MEDIAN change across all cells --
     a uniform shift is machine state, and it cancels within a run because both languages
     are measured under it.
  2. The residual change after removing that uniform shift. This is the part that does
     NOT cancel, and it is what actually moves a verdict.
  3. Verdict stability: for each canonical pairing, the C++-minus-C# gap in each run, and
     whether the two runs agree on direction and magnitude.

Usage: python scripts/between_runs.py <git-ref-of-run-A>
       python scripts/between_runs.py c2ffe18
"""

from __future__ import annotations

import glob
import json
import pathlib
import statistics
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"

# Windows configs only: the Linux binaries DID change between the two runs
# (-fno-stack-protector was added), so those matrices are not comparable this way.
WINDOWS_CFGS = ["cpp-msvc1444", "cpp-msvc1451", "jit-tc0", "jit-qjfl",
                "jit-qjfl-nogc", "jit-default", "aot"]

# (label, cpp_bench, cs_bench) -- mirrors CANONICAL in analyze.py
PAIRINGS = [
    ("order book / idiomatic C#", "orderbook_l2", "orderbook_l2_safe"),
    ("order book / tuned C#", "orderbook_l2", "orderbook_l2_opt2"),
    ("FIX same-source / idiomatic C#", "fix_parse", "fix_parse_safe"),
    ("FIX equal-effort / idiomatic C#", "fix_parse_simd", "fix_parse_safe_simd"),
    ("FIX parser only, no checksum", "fix_parse_nosum", "fix_parse_nosum"),
]
CS_CANON = "jit-tc0"
CPP_CFGS = ["cpp-msvc1444", "cpp-msvc1451"]


def cell_medians(directory: pathlib.Path) -> dict[tuple[str, str], float]:
    """(config, bench) -> median of that cell's per-launch medians."""
    per_cell: dict[tuple[str, str], list[float]] = {}
    for path in glob.glob(str(directory / "proc-*.json")):
        try:
            doc = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
        except Exception:
            continue
        cfg = doc.get("runtime")
        if cfg not in WINDOWS_CFGS:
            continue
        for b in doc["benchmarks"]:
            per_cell.setdefault((cfg, b["name"]), []).append(
                statistics.median(b["nsPerOpSeries"]))
    return {k: statistics.median(v) for k, v in per_cell.items() if len(v) >= 11}


def extract_run(ref: str, dest: pathlib.Path) -> pathlib.Path:
    """Pull results/ out of a git ref without touching the working tree."""
    proc = subprocess.run(["git", "archive", ref, "results"],
                          cwd=ROOT, capture_output=True)
    if proc.returncode != 0:
        sys.exit(f"git archive {ref} failed: {proc.stderr.decode()[:300]}")
    tar = subprocess.run(["tar", "-x", "-C", str(dest)], input=proc.stdout,
                         capture_output=True)
    if tar.returncode != 0:
        sys.exit(f"tar extract failed: {tar.stderr.decode()[:300]}")
    return dest / "results"


def main() -> int:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    ref = sys.argv[1]

    with tempfile.TemporaryDirectory() as tmp:
        a = cell_medians(extract_run(ref, pathlib.Path(tmp)))
    b = cell_medians(RESULTS)

    shared = sorted(set(a) & set(b))
    if not shared:
        sys.exit("no overlapping Windows cells between the two runs")

    changes = {k: (b[k] - a[k]) / a[k] * 100 for k in shared}
    shift = statistics.median(changes.values())

    out = []
    P = out.append
    P("# Does the verdict survive re-running the experiment?\n")
    P(f"Run A = `{ref}`, run B = current `results/`. Windows cells only: the Linux "
      "binaries changed between these two matrices, so they are not comparable this "
      "way.\n")
    P("_Generated by `scripts/between_runs.py`; do not hand-edit._\n")

    P("## 1. The uniform component\n")
    P(f"Across **{len(shared)} cells**, the median change from run A to run B is "
      f"**{shift:+.1f}%**, spanning [{min(changes.values()):+.1f}%, "
      f"{max(changes.values()):+.1f}%].\n")
    P("A change common to every cell is machine state, not language, and it cancels "
      "inside a single matrix because both languages are measured under it. What does "
      "not cancel is the spread AROUND it.\n")

    P("## 2. What moved after removing the uniform shift\n")
    P("| config | benchmark | run A | run B | change | residual vs the shift |")
    P("|---|---|---|---|---|---|")
    resid = {k: changes[k] - shift for k in shared}
    for k in sorted(shared, key=lambda k: abs(resid[k]), reverse=True):
        if abs(resid[k]) >= 4.0:
            P(f"| `{k[0]}` | `{k[1]}` | {a[k]:.2f} | {b[k]:.2f} | {changes[k]:+.1f}% | "
              f"**{resid[k]:+.1f}pp** |")
    P("")
    med_abs = statistics.median([abs(x) for x in resid.values()])
    P(f"Residual spread: median |residual| = {med_abs:.1f}pp, "
      f"max = {max(abs(x) for x in resid.values()):.1f}pp across {len(resid)} cells.\n")
    P("**Read this as the floor on any claim.** An effect smaller than the residual "
      "spread cannot be told apart from the machine having a different afternoon, no "
      "matter how tight the within-matrix interval looks.\n")

    P("## 3. Verdict stability\n")
    P("The gap each run reports for the same pre-declared pairing. Gap is C# relative to "
      "C++, so positive means C++ is faster.\n")
    P("| pairing | C++ config | gap in run A | gap in run B | stable? |")
    P("|---|---|---|---|---|")
    for label, cpp_bench, cs_bench in PAIRINGS:
        for cpp_cfg in CPP_CFGS:
            ka, kb = (cpp_cfg, cpp_bench), (CS_CANON, cs_bench)
            if not (ka in a and ka in b and kb in a and kb in b):
                continue
            ga = (a[kb] / a[ka] - 1) * 100
            gb = (b[kb] / b[ka] - 1) * 100
            spread = abs(ga - gb)
            if (ga > 0) != (gb > 0):
                verdict = "**SIGN FLIPPED**"
            elif spread < 5:
                verdict = "**stable**"
            else:
                verdict = f"same direction, magnitude moved {spread:.0f}pp"
            P(f"| {label} | `{cpp_cfg}` | {ga:+.1f}% | {gb:+.1f}% | {verdict} |")
    P("")

    text = "\n".join(out) + "\n"
    sys.stdout.write(text)
    (RESULTS / "REPRODUCIBILITY.md").write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
